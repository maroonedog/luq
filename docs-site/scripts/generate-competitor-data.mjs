// ===========================================================================
// docs-site/scripts/generate-competitor-data.mjs
//
// Generates the competitor data the site reads, from the recorded comparison.
//
// One source: the file the competitor benchmark ran and wrote. The site holds
// no figures of its own, so that it cannot repeat the staleness that already
// happened with the pass rate, the version and the bundle sizes.
//
// No formatting that shows only the wins. A row where this library is slower
// goes in the same table.
//
// The machine is not copied through. This table compares libraries, not
// machines, and naming one makes the machine the argument.
// ===========================================================================
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPOSITORY_ROOT = join(HERE, "..", "..");
const BASELINE = join(REPOSITORY_ROOT, "config", "competitor-baseline.json");
const OUTPUT = join(HERE, "..", "src", "data", "competitors.ts");

const HEADER = `// GENERATED by scripts/generate-competitor-data.mjs — do not edit.
// Source of truth: config/competitor-baseline.json, written by
// bench/competitors/report-competitors.ts.
`;

/** Measurements arrive as floats. Display is a rounded string fixed here, so
 *  no page gets to choose its own precision. */
function toOps(value) {
  return Math.round(value).toLocaleString("en-US");
}

function toRatio(value) {
  return value >= 10 ? value.toFixed(0) : value.toFixed(2);
}

function run() {
  const baseline = JSON.parse(readFileSync(BASELINE, "utf8"));

  const rows = baseline.measured.map((entry) => ({
    shape: entry.shape,
    competitor: entry.competitor,
    version: entry.competitorVersion,
    luq: toOps(entry.luqOpsPerSecond),
    other: toOps(entry.competitorOpsPerSecond),
    ratio: toRatio(entry.ratio),
    luqIsFaster: entry.ratio >= 1,
    comparedValues: entry.comparedValues,
    disagreedValues: entry.disagreedValues,
  }));

  const disagreements = baseline.agreement
    .filter((entry) => entry.disagreements.length > 0)
    .flatMap((entry) =>
      entry.disagreements.map((one) => ({
        shape: entry.shape,
        competitor: entry.competitor,
        luqSaid: one.luqSaid,
        value: one.value,
      }))
    );

  const body = [
    HEADER,
    "export const competitorBenchmark = {",
    `  libraries: ${JSON.stringify(baseline.competitors)},`,
    `  rows: ${JSON.stringify(rows, null, 2).replace(/\n/g, "\n  ")},`,
    `  disagreements: ${JSON.stringify(disagreements, null, 2).replace(/\n/g, "\n  ")},`,
    `  luqWins: ${rows.filter((row) => row.luqIsFaster).length},`,
    `  total: ${rows.length},`,
    "} as const;",
    "",
  ].join("\n");

  writeFileSync(OUTPUT, body, "utf8");
  console.log(
    `src/data/competitors.ts: ${rows.length} rows, Luq faster in ${
      rows.filter((row) => row.luqIsFaster).length
    }`
  );
}

run();
