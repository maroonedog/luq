// ===========================================================================
// docs-site/scripts/generate-size-data.mjs
//
// src/data/bundle-size.ts を config/size-budget.json から生成する。
//
// なぜ生成するのか。同じ数字がサイトの7箇所と README に手で書かれていて、
// そして実際に古くなった: 2.1.0 の作業でコアが 7,420 B から 7,590 B に増えた
// のに、どこも直っていなかった。サイズのゲートは **天井** であって等号では
// ないので、170 B のずれでは何も落ちない。
//
// 適合率 (generate-conformance-data.mjs) とバージョン
// (generate-package-data.mjs) に続いて三度目の同じ腐り方なので、同じ直し方を
// する。出所は config/size-budget.json ただ一つで、そこは
// scripts/measure-bundle-size.ts が天井として読む場所でもある。
// ===========================================================================
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPOSITORY_ROOT = join(HERE, "..", "..");
const BUDGET_FILE = join(REPOSITORY_ROOT, "config", "size-budget.json");
const OUTPUT_FILE = join(HERE, "..", "src", "data", "bundle-size.ts");

const HEADER = `// GENERATED by scripts/generate-size-data.mjs — do not edit.
// Source of truth: config/size-budget.json, which scripts/measure-bundle-size.ts
// re-measures against on every build.
`;

/** 3桁区切り。サイトは常にこの形で出す。 */
function withSeparators(bytes) {
  return bytes.toLocaleString("en-US");
}

const CAMEL_BY_ID = {
  "core-only": "coreOnly",
  "one-plugin": "onePlugin",
  "three-plugin": "threePlugin",
  "six-plugin": "sixPlugin",
  "preset-presence": "presetPresence",
  "preset-everyday": "presetEveryday",
  "jsonschema-plugin": "jsonSchemaPlugin",
  "jsonschema-full-feature": "jsonSchemaFullFeature",
  "full-feature": "fullFeature",
};

function run() {
  const budget = JSON.parse(readFileSync(BUDGET_FILE, "utf8"));
  const lines = [HEADER, "export const bundleSize = {"];

  for (const entry of budget.budgets) {
    const name = CAMEL_BY_ID[entry.id];
    if (name === undefined) continue;
    const bytes = entry.recordedGzipBytes;
    lines.push(`  ${name}: {`);
    lines.push(`    bytes: ${bytes},`);
    lines.push(`    gzip: ${JSON.stringify(`${withSeparators(bytes)} B`)},`);
    lines.push(`    ceiling: ${entry.gzipCeilingBytes},`);
    lines.push("  },");
  }

  const legacy = budget.legacyBaseline ?? {};
  lines.push(`  legacyCoreGzip: ${JSON.stringify(legacy.coreOnlyGzipBytes ?? 17423)},`);
  lines.push("} as const;");
  lines.push("");

  writeFileSync(OUTPUT_FILE, lines.join("\n"), "utf8");
  console.log(
    `src/data/bundle-size.ts: core ${withSeparators(
      budget.budgets.find((entry) => entry.id === "core-only").recordedGzipBytes
    )} B`
  );
}

run();
