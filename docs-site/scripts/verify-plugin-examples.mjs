// Compiles every usage example in plugin-copy.mjs against the repository's own
// src/, so a chain shown on /plugins cannot be a chain that does not typecheck.
//
// The 1.x data file shipped `b.object.object()`, `b.string.tupleBuilder(...)`
// and `b.string.dependentSchemas("value")` — none of which compile — because
// nothing ever tried to compile them. This is the step that was missing.
//
// It writes one scratch file holding all the chains in a single builder and
// runs the repository's own tsc over it at the repository's own strictness.

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { PLUGIN_COPY } from "./plugin-copy.mjs";
import { readPluginCatalog } from "./read-plugin-catalog.mjs";

const SCRIPTS_DIRECTORY = dirname(fileURLToPath(import.meta.url));
const DOCS_SITE_ROOT = dirname(SCRIPTS_DIRECTORY);
const REPOSITORY_ROOT = dirname(DOCS_SITE_ROOT);
const SCRATCH_DIRECTORY = join(DOCS_SITE_ROOT, ".plugin-example-check");
const SCRATCH_FILE = join(SCRATCH_DIRECTORY, "plugin-examples.ts");

const TSC_OPTIONS = [
  "--noEmit",
  "--strict",
  "--target",
  "ES2020",
  "--lib",
  "ES2020",
  "--module",
  "ESNext",
  "--moduleResolution",
  "bundler",
  "--skipLibCheck",
  "--esModuleInterop",
];

/** A published specifier is a relative src/ path when compiled in-repo. */
function toSourceSpecifier(line, directoryByName) {
  return line.replace(/"@maroonedog\/luq\/plugins\/(\w+)"/g, (whole, name) => {
    const directory = directoryByName.get(name);
    return directory === undefined ? whole : `"../../${directory}"`;
  });
}

function unique(lines) {
  return [...new Set(lines)];
}

/**
 * One builder per example, holding only the plugin and its `uses` list. That
 * is what proves a snippet shown on /plugins compiles on its own — a single
 * shared bag would hide a missing `.use()`.
 */
function buildSourceFile(catalog) {
  const directoryByName = new Map(
    catalog.map((plugin) => [plugin.name, plugin.directory])
  );
  const symbols = new Set(catalog.map((plugin) => plugin.symbol));
  const imports = ['import { Builder } from "../../src";'];
  const preludes = [];
  const bodies = [];

  for (const plugin of catalog) {
    const { example } = PLUGIN_COPY[plugin.symbol];
    imports.push(
      `import { ${plugin.symbol} } from "../../${plugin.directory}";`
    );
    for (const line of example.imports ?? []) {
      imports.push(toSourceSpecifier(line, directoryByName));
    }
    if (example.prelude !== undefined)
      preludes.push(example.prelude.join("\n"));

    for (const used of example.uses) {
      const dependency = catalog.find((entry) => entry.symbol === used);
      if (dependency === undefined || !symbols.has(used)) {
        throw new Error(
          `${plugin.symbol}: uses names an unknown plugin ${used}`
        );
      }
      // Guards against a stale `uses` entry: tsc proves the list is long
      // enough, this proves it is not longer than the chain needs.
      if (!example.chain.includes(`.${dependency.method}(`)) {
        throw new Error(
          `${plugin.symbol}: uses lists ${used}, but the chain never calls .${dependency.method}()`
        );
      }
    }

    bodies.push(
      [
        `type Example_${plugin.symbol} = {`,
        ...unique(example.declarations).map((line) => `  ${line}`),
        "};",
        `export const validator_${plugin.symbol} = Builder()`,
        ...[plugin.symbol, ...example.uses].map(
          (symbol) => `  .use(${symbol})`
        ),
        `  .for<Example_${plugin.symbol}>()`,
        `  .v("${example.field}", (b) => b.${example.chain})`,
        "  .build();",
      ].join("\n")
    );
  }

  return [
    "// GENERATED by docs-site/scripts/verify-plugin-examples.mjs. Do not edit.",
    ...unique(imports),
    "",
    ...unique(preludes),
    "",
    ...bodies,
    "",
  ].join("\n");
}

/** docs-site carries its own typescript; the repository root carries one too. */
function findCompiler() {
  const candidates = [DOCS_SITE_ROOT, REPOSITORY_ROOT].map((root) =>
    join(root, "node_modules/typescript/bin/tsc")
  );
  const found = candidates.find((candidate) => existsSync(candidate));
  if (found === undefined) {
    throw new Error(`no typescript found in: ${candidates.join(", ")}`);
  }
  return found;
}

function run() {
  const catalog = readPluginCatalog(REPOSITORY_ROOT);
  mkdirSync(SCRATCH_DIRECTORY, { recursive: true });
  writeFileSync(SCRATCH_FILE, buildSourceFile(catalog), "utf8");
  try {
    execFileSync(
      process.execPath,
      [findCompiler(), ...TSC_OPTIONS, SCRATCH_FILE],
      { cwd: REPOSITORY_ROOT, stdio: "inherit" }
    );
  } catch (error) {
    console.error(`Kept for inspection: ${SCRATCH_FILE}`);
    throw error;
  }
  rmSync(SCRATCH_DIRECTORY, { recursive: true, force: true });
  console.log(`${catalog.length} plugin examples typecheck against src/.`);
}

run();
