// ===========================================================================
// docs-site/scripts/generate-conformance-data.mjs
//
// src/data/conformance.ts を config/json-schema-suite.json から生成する。
//
// なぜ生成するのか。この数字はページに直接書かれていて、そして実際に古く
// なった: 適合率が 855/929 に上がったあとも、トップページ・/json-schema・
// /roadmap の3箇所が 828/929 = 89.13% を表示し続けていた。3箇所とも「読めば
// 分かる」種類の誤りで、誰も読まなかった。プラグイン一覧を生成しているのと
// 同じ理由で、これも手で写すのをやめる。
//
// config/json-schema-suite.json は test/integration/json-schema-suite.test.ts
// が両方向に表明している (退行も未記録の改善もビルドを落とす) ので、ここが
// 唯一の出所として正しい。
// ===========================================================================
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPOSITORY_ROOT = join(HERE, "..", "..");
const PIN_FILE = join(REPOSITORY_ROOT, "config", "json-schema-suite.json");
const OUTPUT_FILE = join(HERE, "..", "src", "data", "conformance.ts");

const HEADER = `// GENERATED by scripts/generate-conformance-data.mjs — do not edit.
// Source of truth: config/json-schema-suite.json, which
// test/integration/json-schema-suite.test.ts asserts in both directions.
`;

/** 小数第2位まで。表示に使う唯一の丸め方をここに閉じ込める。 */
function toPercent(passing, total) {
  return ((passing / total) * 100).toFixed(2);
}

function run() {
  const pin = JSON.parse(readFileSync(PIN_FILE, "utf8"));
  const {
    passingCases,
    caseCount,
    skippedCases,
    commit,
    contentDigest,
    fileCount,
    groupCount,
    validCases,
    invalidCases,
    passingValidCases,
    passingInvalidCases,
  } = pin;
  if (typeof passingCases !== "number" || typeof caseCount !== "number") {
    throw new Error("config/json-schema-suite.json: 件数が読めない");
  }
  const percent = toPercent(passingCases, caseCount);

  const body = [
    HEADER,
    "export const conformance = {",
    `  passingCases: ${passingCases},`,
    `  caseCount: ${caseCount},`,
    `  failingCases: ${caseCount - passingCases},`,
    `  skippedCases: ${skippedCases},`,
    `  percent: ${JSON.stringify(percent)},`,
    `  fraction: ${JSON.stringify(`${passingCases} / ${caseCount}`)},`,
    `  headline: ${JSON.stringify(`${passingCases} / ${caseCount} = ${percent}%`)},`,
    `  suiteCommit: ${JSON.stringify(commit)},`,
    `  suiteDigest: ${JSON.stringify(contentDigest)},`,
    `  fileCount: ${fileCount},`,
    `  groupCount: ${groupCount},`,
    // 「常に true を返すだけの検証器」との比較。適合率はこの下限と
    // 並べて初めて意味を持つので、内訳も同じ出所から出す。
    `  validCases: ${validCases},`,
    `  invalidCases: ${invalidCases},`,
    `  passingValidCases: ${passingValidCases},`,
    `  passingInvalidCases: ${passingInvalidCases},`,
    `  validPercent: ${JSON.stringify(toPercent(passingValidCases, validCases))},`,
    `  invalidPercent: ${JSON.stringify(toPercent(passingInvalidCases, invalidCases))},`,
    `  trivialPercent: ${JSON.stringify(toPercent(validCases, caseCount))},`,
    "} as const;",
    "",
  ].join("\n");

  writeFileSync(OUTPUT_FILE, body, "utf8");
  console.log(`src/data/conformance.ts: ${passingCases}/${caseCount} = ${percent}%`);
}

run();
