// ===========================================================================
// docs-site/scripts/generate-package-data.mjs
//
// Generates the package data the site reads, from the repository package.json.
//
// Why generate it. The version was typed into several pages independently, and
// it went stale after a release — with the next release, all of them would
// have to be remembered again. An outside review once reported the site still
// advertising a long-superseded alpha, which was the same copying.
//
// One source. What package.json says is what npm serves, which makes it the
// only correct one.
//
// Two of the figures here are counts, and they were typed by hand on three
// pages before they moved in here — "762 emitted modules" and "84 export keys"
// against 836 and 88 actually shipped. They sit on the cards whose whole point
// is that nothing on this site is typed by hand, so they are counted instead.
//
// moduleCount reads a BUILD OUTPUT, which is the one thing package.json cannot
// tell us. That makes this generator order-dependent: `npm run generate-all`
// only produces a true count if the package was built first. A missing or
// empty dist/ must therefore be an error, never a zero — a zero would be
// published onto the headline CSP card as though it had been measured.
// ===========================================================================
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPOSITORY_ROOT = join(HERE, "..", "..");
const PACKAGE_FILE = join(REPOSITORY_ROOT, "package.json");
const DIST_DIRECTORY = join(REPOSITORY_ROOT, "dist");
const OUTPUT_FILE = join(HERE, "..", "src", "data", "package-info.ts");

const EMITTED_MODULE_SUFFIXES = [".js", ".mjs"];

const HEADER = `// GENERATED by scripts/generate-package-data.mjs — do not edit.
// Source of truth: the repository's package.json, which is what npm publishes,
// and the emitted modules under dist/, which is what it publishes them from.
`;

/**
 * Every emitted module under dist/, counted by walking the tree. `.d.ts` files
 * are declarations rather than modules and are not counted.
 */
function countEmittedModules(directory) {
  let entries;
  try {
    entries = readdirSync(directory, { withFileTypes: true });
  } catch (cause) {
    throw new Error(
      `dist/ could not be read at ${directory}. moduleCount is a count of ` +
        "build output, so the package has to be built before this generator " +
        "runs: `npm run build` at the repository root, then `npm run " +
        "generate-all` here.",
      { cause }
    );
  }

  let total = 0;
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      total += countEmittedModules(path);
      continue;
    }
    if (EMITTED_MODULE_SUFFIXES.some((suffix) => entry.name.endsWith(suffix))) {
      total += 1;
    }
  }
  return total;
}

function run() {
  const manifest = JSON.parse(readFileSync(PACKAGE_FILE, "utf8"));
  const { name, version, exports } = manifest;
  if (typeof name !== "string" || typeof version !== "string") {
    throw new Error("package.json: name or version is unreadable");
  }
  if (exports === null || typeof exports !== "object") {
    throw new Error("package.json: exports is unreadable");
  }

  const exportKeyCount = Object.keys(exports).length;
  if (exportKeyCount === 0) {
    throw new Error("package.json: exports is empty");
  }

  const moduleCount = countEmittedModules(DIST_DIRECTORY);
  if (moduleCount === 0) {
    throw new Error(
      `dist/ holds no .js or .mjs file at ${DIST_DIRECTORY}. That is an ` +
        "unbuilt or half-cleaned tree, not a package with no modules — " +
        "build the package first rather than publishing a zero onto the site."
    );
  }

  const body = [
    HEADER,
    "export const packageInfo = {",
    `  name: ${JSON.stringify(name)},`,
    `  version: ${JSON.stringify(version)},`,
    `  tag: ${JSON.stringify(`v${version}`)},`,
    `  install: ${JSON.stringify(`npm install ${name}`)},`,
    "  /** Emitted .js/.mjs modules under dist/, counted at generation time. */",
    `  moduleCount: ${moduleCount},`,
    "  /** Keys of package.json#exports — every specifier a consumer can import. */",
    `  exportKeyCount: ${exportKeyCount},`,
    "} as const;",
    "",
  ].join("\n");

  writeFileSync(OUTPUT_FILE, body, "utf8");
  console.log(
    `src/data/package-info.ts: ${name}@${version}, ` +
      `${moduleCount} emitted modules, ${exportKeyCount} export keys`
  );
}

run();
