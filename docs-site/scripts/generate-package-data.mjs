// ===========================================================================
// docs-site/scripts/generate-package-data.mjs
//
// src/data/package-info.ts を、リポジトリの package.json から生成する。
//
// なぜ生成するのか。バージョン表記はページに直接書かれていて、そして実際に
// 古くなった: 2.0.0 を公開したあとも、トップ・フッター・getting-started の
// 3箇所が別々に手で書かれており、次に上げるときは3箇所を思い出さなければ
// ならない。外部レビューが「v0.1.0-alpha のまま」と指摘したのも、元をたどれば
// 同じ種類の写しである。
//
// 出所は package.json ただ一つ。npm に出るのはその値なので、そこが唯一の
// 正しい出所である。
// ===========================================================================
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPOSITORY_ROOT = join(HERE, "..", "..");
const PACKAGE_FILE = join(REPOSITORY_ROOT, "package.json");
const OUTPUT_FILE = join(HERE, "..", "src", "data", "package-info.ts");

const HEADER = `// GENERATED by scripts/generate-package-data.mjs — do not edit.
// Source of truth: the repository's package.json, which is what npm publishes.
`;

function run() {
  const manifest = JSON.parse(readFileSync(PACKAGE_FILE, "utf8"));
  const { name, version } = manifest;
  if (typeof name !== "string" || typeof version !== "string") {
    throw new Error("package.json: name か version が読めない");
  }

  const body = [
    HEADER,
    "export const packageInfo = {",
    `  name: ${JSON.stringify(name)},`,
    `  version: ${JSON.stringify(version)},`,
    `  tag: ${JSON.stringify(`v${version}`)},`,
    `  install: ${JSON.stringify(`npm install ${name}`)},`,
    "} as const;",
    "",
  ].join("\n");

  writeFileSync(OUTPUT_FILE, body, "utf8");
  console.log(`src/data/package-info.ts: ${name}@${version}`);
}

run();
